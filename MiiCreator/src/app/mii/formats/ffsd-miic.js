function validateMiiFields(e, t) {
  let r = !0,
    n = [];
  return (
    Object.keys(e).forEach((i) => {
      function o(a = i, l) {
        ((r = !1), n.push({ reason: l, prop: a }));
      }
      let s = MII_FIELD_LIMITS[i];
      if (!s) {
        alert("A prop is missing: " + i);
        return;
      }
      if ((i === "nickname" && (t & 1) === 1) || (t & 2) === 2) return;
      if (e.personality === 24 && (i === "height" || i === "build")) {
        let a = e[i];
        if (a > 255 || a < 0) o(i, "is not within ghost value");
        else return;
      }
      switch (s.type) {
        case 0: {
          let a = e[i];
          if (a < s.min) o(i, `(${a}) is below minimum value`);
          if (a > s.max) o(i, `(${a}) is above maximum value`);
          break;
        }
        case 1: {
          let a = e[i];
          if (a.trim().length < s.min) o(i, `(${a}) is below minimum length`);
          if (a.trim().length > s.max) o(i, `(${a}) is above maximum length`);
          break;
        }
        case 2: {
          let a = e[i];
          if (a.length !== s.size) o(i, `size is ${a.length}, expected ${s.size}`);
          if (Array.from(a).every((l) => l >= s.min && l <= s.max) === !1) o();
          break;
        }
      }
    }),
    { valid: r, reasons: n }
  );
}
